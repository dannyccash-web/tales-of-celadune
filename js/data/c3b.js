// RESIZED TO 4000x4000 (2026-09-24, round 4): Danny replaced all three temple
// background images with 4000x4000 versions of the SAME art (bigger canvas,
// same composition — confirmed by eye: the stained-glass medallion, all four
// corner rooms, and the SW staircase are pixel-for-pixel the same layout,
// just rendered ~4/3 larger) so the temple reads as a bigger space. Every
// coordinate below is the old 3000-wide value scaled by 4/3 EXCEPT `spawn`,
// which is recomputed as the new image's exact centre (2000,2000) rather
// than 1500*4/3, for the same reason as before: it needs to land exactly
// under the light shaft, not just proportionally close. Collision was fully
// regenerated from the new image (see below), NOT scaled from the old rects
// — a straight numeric scale of rects would have been faster but would have
// silently carried over any old misclassification and wouldn't reflect
// whatever the upscale changed at the pixel level. Every interactable
// coordinate was individually re-verified walkable against the FRESH
// collision (not assumed from the scale factor) — see the "Verified" note
// at the bottom.
//
// World coordinates 4000x4000, matching C3B_Background_1.jpg 1:1 (same
// convention as every other scene). `spawn` is the exact centre of the art
// (2000,2000) — the middle of the stained-glass medallion, directly under
// the light shaft, per Danny's spec ("take them to the center of
// C3B_Background_1.jpg").
//
// Collision generated from C3B_Background_1.jpg: per-20px-cell scan of the
// max colour channel (mean over each cell), thresholded at 24 (same
// threshold as the 3000px version — this image's brightness profile matches
// closely enough that no recalibration was needed, unlike Level 3 below) to
// separate void from painted floor/wall, largest 4-connected component kept
// as the walkable region, small (<6-cell) noise islands on the blocked side
// folded back into the walkable region, then merged into rects via row-run +
// row-stack (same recipe used throughout this project). 589 rects (up from
// 375 at 3000px — a bigger canvas at the same cell size means more, smaller
// rects, not a denser or noisier read). Verified headlessly (replicating
// world.js's circleRectOverlap, 18px collider radius): a BFS/connected-
// component check from spawn reaches the stairs-down trigger and a spread of
// perimeter rooms; the centre medallion overlay was visually re-checked and
// is fully walkable with no misclassified bleed.

